import { useRef } from "react";
import type { Sale } from "@/types/books";
import { paymentLabels } from "@/lib/books";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Separator } from "@/components/ui/separator";
import { formatRupiah } from "@/lib/currency";
import { Download, Share2, Building, Phone, MapPin, FileText } from "lucide-react";
import html2canvas from "html2canvas";
import jsPDF from "jspdf";
import { toast } from "sonner";
import { isBusinessLogo } from "@/lib/branding";
import { useAuth } from "@/contexts/AuthContext";

interface InvoiceModalProps {
  sale: Sale | null;
  isOpen: boolean;
  onClose: () => void;
}

export const InvoiceModal = ({ sale, isOpen, onClose }: InvoiceModalProps) => {
  const invoiceRef = useRef<HTMLDivElement>(null);
  const { user } = useAuth();

  if (!sale) return null;
  const buyerName = sale.customer.name || "Pelanggan";

  const formatDate = (date: string) => {
    return new Date(date).toLocaleDateString("id-ID", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  };

  const downloadInvoice = async () => {
    if (!invoiceRef.current) return;

    try {
      // Capture the invoice as canvas with better settings for full content
      const canvas = await html2canvas(invoiceRef.current, {
        backgroundColor: "#ffffff",
        scale: 2, // Balanced resolution
        useCORS: true,
        allowTaint: true,
        logging: false,
        height: invoiceRef.current.scrollHeight, // Capture full height
        windowHeight: invoiceRef.current.scrollHeight, // Ensure full content is rendered
      });

      // Create PDF
      const pdf = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      // A4 dimensions
      const pdfWidth = 210; // A4 width in mm
      const pdfHeight = 297; // A4 height in mm
      const margin = 15; // Smaller margin for more content space
      const contentWidth = pdfWidth - (margin * 2);
      
      // Calculate image dimensions
      const imgWidth = contentWidth;
      const imgHeight = (canvas.height * imgWidth) / canvas.width;
      
      const imgData = canvas.toDataURL('image/png', 1.0); // Use PNG for better quality
      
      // If content is taller than one page, split it across multiple pages
      if (imgHeight > (pdfHeight - margin * 2)) {
        const pageHeight = pdfHeight - margin * 2;
        const totalPages = Math.ceil(imgHeight / pageHeight);
        
        for (let i = 0; i < totalPages; i++) {
          if (i > 0) {
            pdf.addPage();
          }
          
          const sourceY = (i * pageHeight * canvas.height) / imgHeight;
          const sourceHeight = (pageHeight * canvas.height) / imgHeight;
          
          // Create a temporary canvas for this page
          const pageCanvas = document.createElement('canvas');
          const pageCtx = pageCanvas.getContext('2d');
          pageCanvas.width = canvas.width;
          pageCanvas.height = sourceHeight;
          
          if (pageCtx) {
            pageCtx.drawImage(canvas, 0, sourceY, canvas.width, sourceHeight, 0, 0, canvas.width, sourceHeight);
            const pageImgData = pageCanvas.toDataURL('image/png', 1.0);
            pdf.addImage(pageImgData, 'PNG', margin, margin, imgWidth, pageHeight);
          }
        }
      } else {
        // Single page - center vertically if smaller than page
        const yPosition = margin;
        pdf.addImage(imgData, 'PNG', margin, yPosition, imgWidth, imgHeight);
      }

      // Add footer on the last page
      pdf.setFontSize(8);
      pdf.setTextColor(150, 150, 150);
      pdf.text('Generated by Reseller Manager', margin, pdfHeight - 8);

      // Download PDF with readable filename
      const fileName = `Invoice-${buyerName.replace(/[^a-zA-Z0-9]/g, '')}-${sale.number}.pdf`;
      pdf.save(fileName);

      toast.success("Invoice PDF berhasil diunduh");
    } catch (error) {
      toast.error("Gagal mengunduh invoice PDF");
      console.error(error);
    }
  };

  const shareToWhatsApp = async () => {
    if (!invoiceRef.current) return;

    try {
      const canvas = await html2canvas(invoiceRef.current, {
        backgroundColor: "#ffffff",
        scale: 2,
      });

      canvas.toBlob((blob) => {
        if (!blob) {
          toast.error("Gagal membuat gambar");
          return;
        }

        const file = new File([blob], `invoice-${sale.number}.png`, { type: "image/png" });

        if (navigator.share && navigator.canShare({ files: [file] })) {
          navigator
            .share({
              files: [file],
              title: `Invoice - ${buyerName}`,
              text: `Invoice untuk ${buyerName}`,
            })
            .then(() => toast.success("Berhasil dibagikan"))
            .catch(() => toast.error("Gagal membagikan"));
        } else {
          const itemsList = sale.items.map(item => 
            `${item.name}${item.option ? ` (${item.option})` : ""} (${item.quantity}x) - ${formatRupiah(item.unitPrice * item.quantity)}`
          ).join("\n") || "";
          
          const businessHeader = user?.businessName ? `*${user.businessName}*\n` : "";
          const businessContact = user?.businessPhone ? `📞 ${user.businessPhone}\n` : "";
          const paymentInfo = user?.bankAccounts?.filter(account => account.bankName && account.accountNumber).length 
            ? `\n💳 *Pembayaran Transfer:*\n${user.bankAccounts
                .filter(account => account.bankName && account.accountNumber)
                .map(account => `Bank: ${account.bankName}\nNo. Rek: ${account.accountNumber}${account.accountHolder ? `\nA.n: ${account.accountHolder}` : ""}`)
                .join('\n\n')}`
            : "";
          
          const message = encodeURIComponent(
            `${businessHeader}${businessContact}\n*INVOICE ${sale.number}*\n\nPembeli: ${buyerName}\n\nProduk:\n${itemsList}\n\nTotal: ${formatRupiah(sale.total)}\nStatus: ${paymentLabels[sale.paymentState]}${sale.balance > 0 ? `\nSisa bayar: ${formatRupiah(sale.balance)}` : ""}${paymentInfo}\n\nTerima kasih!`
          );
          window.open(`https://wa.me/?text=${message}`, "_blank");
        }
      });
    } catch (error) {
      toast.error("Gagal membagikan invoice");
      console.error(error);
    }
  };

  return (
    <Dialog open={isOpen} onOpenChange={onClose}>
      <DialogContent className="max-w-md max-h-[90vh] flex flex-col">
        <DialogHeader className="flex-shrink-0">
          <DialogTitle>Invoice</DialogTitle>
        </DialogHeader>

        <div className="flex-1 overflow-y-auto pr-2 scrollbar-hide">
          <div ref={invoiceRef} className="invoice-paper bg-card p-6 rounded-lg space-y-4">
          {/* Business Header */}
          {isBusinessLogo(user?.businessLogo) && <img src={user.businessLogo} alt="Logo bisnis" className="mx-auto h-14 w-14 object-contain" />}
          <div className="text-center border-b pb-4">
            {user?.businessName && (
              <div className="mb-3">
                <h1 className="text-xl font-bold text-primary">
                  {user.businessName}
                </h1>
                {user.businessAddress && (
                  <div className="flex items-center justify-center gap-1 mt-1">
                    <MapPin className="h-3 w-3 text-muted-foreground" />
                    <p className="text-xs text-muted-foreground">
                      {user.businessAddress}
                    </p>
                  </div>
                )}
                {user.businessPhone && (
                  <div className="flex items-center justify-center gap-1">
                    <Phone className="h-3 w-3 text-muted-foreground" />
                    <p className="text-xs text-muted-foreground">
                      {user.businessPhone}
                    </p>
                  </div>
                )}
              </div>
            )}
            <h2 className="text-2xl font-bold text-primary">INVOICE</h2>
            <p className="text-sm text-muted-foreground mt-1">{sale.number}</p>
          </div>

          <div className="space-y-3">
            <div>
              <p className="text-sm text-muted-foreground">Tanggal</p>
              <p className="font-medium">{formatDate(sale.date)}</p>
            </div>

            <div>
              <p className="text-sm text-muted-foreground">Pembeli</p>
              <p className="font-medium">{buyerName}</p>
            </div>

            <div className="border-t pt-3">
              <p className="text-sm text-muted-foreground mb-2">Produk</p>
              <div className="space-y-3">
                {sale.items.map((item, index) => (
                  <div key={index} className="text-sm space-y-1 pb-2 border-b last:border-b-0">
                    <div className="flex justify-between">
                      <span className="font-medium">{item.name}{item.option ? ` · ${item.option}` : ""}</span>
                      <span className="text-muted-foreground">x{item.quantity}</span>
                    </div>
                    <div className="flex justify-between text-muted-foreground">
                      <span>Harga satuan:</span>
                      <span>{formatRupiah(item.unitPrice)}</span>
                    </div>
                    <div className="flex justify-between font-medium">
                      <span>Subtotal:</span>
                      <span>{formatRupiah(item.unitPrice * item.quantity)}</span>
                    </div>
                  </div>
                ))}
              </div>
            </div>

            <div className="space-y-2 border-t pt-3 text-sm">
              <div className="flex justify-between">
                <span className="text-muted-foreground">Subtotal produk</span>
                <span>{formatRupiah(sale.subtotal)}</span>
              </div>
              {sale.shipping > 0 && (
                <div className="flex justify-between">
                  <span className="text-muted-foreground">Ongkos kirim</span>
                  <span>{formatRupiah(sale.shipping)}</span>
                </div>
              )}
              {sale.discount > 0 && (
                <div className="flex justify-between">
                  <span className="text-muted-foreground">Diskon</span>
                  <span>-{formatRupiah(sale.discount)}</span>
                </div>
              )}
              {sale.payments.map((payment) => (
                <div key={payment.id} className="flex justify-between">
                  <span className="text-muted-foreground">
                    Dibayar {new Date(payment.date).toLocaleDateString("id-ID", { day: "numeric", month: "short" })} · {payment.method}
                  </span>
                  <span>-{formatRupiah(payment.amount)}</span>
                </div>
              ))}
              <div className="flex justify-between">
                <span className="text-muted-foreground">Status</span>
                <span
                  className={`font-semibold ${
                    sale.paymentState === "paid" ? "text-success" : "text-pending"
                  }`}
                >
                  {paymentLabels[sale.paymentState]}
                </span>
              </div>
            </div>

            {sale.notes && (
              <div className="border-t pt-3">
                <p className="text-sm text-muted-foreground">Catatan</p>
                <p className="text-sm mt-1">{sale.notes}</p>
              </div>
            )}

            {/* Payment Information */}
            {(user?.bankAccounts?.length || user?.qrisImageBase64) && (
              <div className="border-t pt-3">
                <p className="text-sm text-muted-foreground mb-3">Informasi Pembayaran</p>
                
                {/* Bank Transfer Details */}
                {user.bankAccounts && user.bankAccounts.length > 0 && (
                  <div className="bg-muted/30 p-3 rounded-lg mb-3">
                    <p className="text-sm font-medium mb-2">Transfer Bank</p>
                    <div className="space-y-2">
                      {user.bankAccounts
                        .filter(account => account.bankName && account.accountNumber)
                        .map((account, index) => (
                          <div key={account.id || index} className="text-xs border-b border-muted/50 pb-2 last:border-b-0 last:pb-0">
                            <p><span className="text-muted-foreground">Bank:</span> {account.bankName}</p>
                            <p><span className="text-muted-foreground">No. Rekening:</span> {account.accountNumber}</p>
                            {account.accountHolder && (
                              <p><span className="text-muted-foreground">A.n:</span> {account.accountHolder}</p>
                            )}
                          </div>
                        ))
                      }
                    </div>
                  </div>
                )}

                {/* QRIS Code */}
                {user.qrisImageBase64 && (
                  <div className="bg-muted/30 p-3 rounded-lg">
                    <p className="text-sm font-medium mb-2">Pembayaran QRIS</p>
                    <div className="flex justify-center">
                      <img
                        src={user.qrisImageBase64}
                        alt="QRIS Code"
                        className="w-32 h-32 object-cover rounded border"
                      />
                    </div>
                    <p className="text-xs text-muted-foreground text-center mt-1">
                      Scan untuk pembayaran digital
                    </p>
                  </div>
                )}
              </div>
            )}

            <div className="border-t pt-3">
              <div className="flex justify-between items-center">
                <span className="font-semibold">{sale.balance > 0 && sale.balance < sale.total ? "Sisa yang harus dibayar" : "Total bayar"}</span>
                <span className="font-bold text-lg text-primary">{formatRupiah(sale.balance > 0 ? sale.balance : sale.total)}</span>
              </div>
            </div>
          </div>

          <div className="text-center text-xs text-muted-foreground border-t pt-4">
            Terima kasih atas pembelian Anda!
          </div>
          </div>
        </div>

        <div className="flex gap-2 mt-4 flex-shrink-0">
          <Button onClick={downloadInvoice} className="flex-1">
            <FileText className="h-4 w-4 mr-2" />
            Unduh PDF
          </Button>
          <Button onClick={shareToWhatsApp} variant="outline" className="flex-1">
            <Share2 className="h-4 w-4 mr-2" />
            Share WA
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
};
